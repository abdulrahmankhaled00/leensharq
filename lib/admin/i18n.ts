/**
 * Dashboard interface strings (Arabic + English).
 * Safe to import from client and server code. Placeholders use {name}; fill them with fmt().
 * Content itself (brand names, project text…) is always edited in both languages separately.
 */

export type AdminLocale = "ar" | "en";
export const ADMIN_LOCALE_COOKIE = "leen_admin_locale";
/** "collapsed" | "expanded": desktop sidebar state, scoped to /admin. */
export const ADMIN_SIDEBAR_COOKIE = "leen_admin_sidebar";
export const DEFAULT_ADMIN_LOCALE: AdminLocale = "ar";

export function isAdminLocale(v: unknown): v is AdminLocale {
  return v === "ar" || v === "en";
}

export function fmt(template: string, vars: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

