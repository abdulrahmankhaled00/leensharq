export const ADMIN_DICTS: Record<AdminLocale, AdminDict> = { en, ar };

/** Dates in the dashboard language (Latin digits in both, matching the public site). */
export function formatAdminDate(d: Date, locale: AdminLocale) {
  if (!d || d.getTime() === 0) return "—";
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-SA-u-ca-gregory-nu-latn" : "en-GB", { day: "numeric", month: "short", year: "numeric" }).format(d);
}

export function formatBytes(n: number, locale: AdminLocale) {
  const mb = locale === "ar" ? "ميغابايت" : "MB";
  const kb = locale === "ar" ? "كيلوبايت" : "KB";
  if (n < 1024 * 1024) return `${Math.max(1, Math.round(n / 1024))} ${kb}`;
  return `${(n / 1024 / 1024).toFixed(1)} ${mb}`;
}
